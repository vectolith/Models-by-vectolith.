SYSTEM = (
    "You are ASH PRIME, a capable assistant with a distinctive voice. You are warm without being "
    "saccharine, curious, direct, and honest about uncertainty. You avoid filler, canned disclaimers and "
    "performed enthusiasm. You do the work rather than describing what you could do. You never claim "
    "experiences, memories or actions you do not have."
)


def stable_id(prefix: str, text: str) -> str:
    return prefix + "-" + hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]


def rows() -> list[dict]:
    tasks: list[dict] = []
    for competency, prompts in CAPABILITY.items():
        for prompt in prompts:
            tasks.append(
                {
                    "id": stable_id("cap", prompt),
                    "competency": competency,
                    "source": "authored-v1",
                    "system": SYSTEM,
                    "prompt": prompt,
                }
            )

    trajectories = ROOT / "data/personality/ash-prime-multiturn-trajectories-v1.jsonl"
    if trajectories.exists():
        for line in trajectories.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            row = json.loads(line)
            turns = row.get("turns") or []
            prompt = next((t.get("text") for t in turns if t.get("role") == "user"), None)
            if not prompt:
                continue
            tasks.append(
                {
                    "id": stable_id("traj", prompt),
                    "competency": "conversation",
                    "source": "multiturn-trajectories-v1",
                    "system": SYSTEM,
                    "prompt": prompt,
                }
            )

    micro = ROOT / "data/personality/ash-prime-behavioral-micro-scenarios-v1.jsonl"
    if micro.exists():
        for line in micro.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            row = json.loads(line)
            prompt = (row.get("prompt") or "").strip()
            for prefix in ("user:", "User:"):
                if prompt.startswith(prefix):
                    prompt = prompt[len(prefix):].strip().strip("'\"")
            if not prompt:
                continue
            tasks.append(
                {
                    "id": stable_id("micro", prompt),
                    "competency": "conversation",
                    "source": "micro-scenarios-v1",
                    "system": SYSTEM,
                    "prompt": prompt,
                }
            )

    # De-duplicate on prompt text while keeping the first, most specific record.
    seen: set[str] = set()
    unique: list[dict] = []
    for task in tasks:
        if task["prompt"] in seen:
            continue
        seen.add(task["prompt"])
        unique.append(task)
    return unique


def main() -> None:
    tasks = rows()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as handle:
        for task in tasks:
            handle.write(json.dumps(task, ensure_ascii=False) + "\n")
    print(json.dumps({"tasks": len(tasks), "output": str(OUT)}, indent=2))


if __name__ == "__main__":
    main()
